/** URL d'un personnage. Le GLB référence sa texture via `Textures/texture-x.png`. */
export function characterUrl(id: CharacterId): string {
  return encodeURI(`${KENNEY_BASE}/${PACKS.characters}/Models/GLB format/character-${id}.glb`);
}

/** URL d'un meuble (le dossier s'appelle « GLTF format » mais contient des .glb). */
export function furnitureUrl(model: FurnitureModel): string {
  return encodeURI(`${KENNEY_BASE}/${PACKS.furniture}/Models/GLTF format/${model}.glb`);
}

